package main // https://leetcode.com/problems/remove-duplicates-from-sorted-array/

// Идея: массив отсортирован, поэтому одинаковые значения стоят рядом и проверять
// "видел ли я это раньше" не нужно — достаточно сравнить с последним уникальным.
// Два индекса: i читает массив, k указывает, куда писать следующее уникальное значение.
// Он же и ответ: сколько уникальных записано, столько позиций занято с начала.
// Время: O(n) — один проход, каждый элемент сравнивается и при необходимости пишется один раз.
// Память: O(1) — кроме двух переменных ничего не выделяется, изменения идут в том же массиве.
// Ловушка: last всегда равен nums[k-1], то есть последнему записанному элементу. Сравнивать
// с предыдущим прочитанным nums[i-1] тоже можно, но тогда легко сбиться, когда подряд идёт
// несколько дубликатов.
func removeDuplicates(nums []int) int {
	last := nums[0] // последний уникальный элемент
	k := 1
	for i := 1; i < len(nums); i++ {
		if last == nums[i] {
			continue
		}

		last = nums[i]
		nums[k] = nums[i]
		k++
	}

	return k
}
