package main // https://leetcode.com/problems/remove-duplicates-from-sorted-array/

// Идея: массив отсортирован, поэтому одинаковые значения стоят рядом и проверять
// "видел ли я это раньше" не нужно — достаточно сравнить с последним записанным, то есть
// с nums[k-1]. Два индекса: i читает массив, k указывает, куда писать следующее уникальное
// значение. Для отсортированного входа сравнение с предыдущим прочитанным nums[i-1] тоже
// работает, но тогда ответ приходится считать отдельно.
// Время: O(n) — один проход, каждый элемент сравнивается и при необходимости пишется один раз.
// Память: O(1) — кроме одного индекса ничего не выделяется, изменения идут в том же массиве.
// Ловушка: k служит сразу двумя вещами — позицией записи и ответом. Начинаем с k = 1 и i = 1,
// потому что первый элемент заведомо уникален и уже стоит на своём месте.
func removeDuplicates(nums []int) int {
	k := 1
	for i := 1; i < len(nums); i++ {
		if nums[k-1] == nums[i] {
			continue
		}

		nums[k] = nums[i]
		k++
	}

	return k
}
