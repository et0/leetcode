package main // https://leetcode.com/problems/squares-of-a-sorted-array/

func abs(x int) int {
	if x < 0 {
		return -x
	}
	return x
}

// Идея: два указателя с концов. Массив отсортирован, поэтому самый большой квадрат даёт
// либо крайний левый элемент (большое по модулю отрицательное), либо крайний правый.
// Сравниваем их по модулю и пишем больший квадрат в конец результата, двигаясь справа налево.
// Время: O(n) — каждый элемент обрабатывается один раз, сортировка не нужна.
// Память: O(n) на результат, его требует само условие; кроме него ничего не выделяется,
// то есть дополнительная память O(1).
// Ловушка: сравнивать нужно модули, а не сами значения: -7 даёт квадрат больше, чем 3.
// Заполнять результат с начала нельзя: минимальный квадрат может оказаться в середине
// массива, а крайние элементы дают максимумы.
func sortedSquares(nums []int) []int {
	out := make([]int, len(nums))
	idx := len(out) - 1

	left, right := 0, len(nums)-1
	for left <= right {
		if abs(nums[left]) > abs(nums[right]) {
			out[idx] = nums[left] * nums[left]
			left++
		} else {
			out[idx] = nums[right] * nums[right]
			right--
		}

		idx--
	}

	return out
}
