package main // https://leetcode.com/problems/merge-sorted-array/

// Идея: сливаем с конца. В nums1 последние n позиций свободны, поэтому запись справа налево
// не затирает непрочитанные элементы. Три указателя: i — последний значащий элемент nums1,
// j — последний элемент nums2, z — позиция записи. На каждом шаге в z пишем больший
// из nums1[i] и nums2[j].
// Инвариант: на каждом шаге z = i + j + 1, потому что за шаг уменьшается z и ровно один
// из i, j. Отсюда следует, что когда j доходит до -1, то z = i: оставшиеся элементы nums1
// уже лежат на своих местах, и докопировать нужно только остаток nums2.
// Время: O(m+n) — каждая позиция записывается один раз.
// Память: O(1) — только три индекса, новых массивов нет.
// Ловушка: заполнение с начала затирает ещё непрочитанные элементы nums1. Пример:
// nums1 = [4,5,6,0,0,0] и nums2 = [1,2,3], единице нужна позиция 0, где лежит четвёрка.
func merge(nums1 []int, m int, nums2 []int, n int) {
	i, j, z := m-1, n-1, m+n-1

	for i >= 0 && j >= 0 {
		if nums1[i] > nums2[j] {
			nums1[z] = nums1[i]
			i--
		} else {
			nums1[z] = nums2[j]
			j--
		}
		z--
	}

	for j >= 0 {
		nums1[z] = nums2[j]
		z--
		j--
	}
}
