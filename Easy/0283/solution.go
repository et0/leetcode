package main // https://leetcode.com/problems/move-zeroes/

// Идея: left — позиция, куда поедет следующий ненулевой элемент, right сканирует массив.
// Нули из массива не выбрасываются, поэтому элементы не затираются, а обмениваются:
// ненулевой уходит на left, а ноль с left уезжает на right.
// Инвариант: пока left меньше right, весь участок nums[left..right-1] состоит из нулей.
// Отсюда видно, почему первая ветка срабатывает только при left равном right: если left
// меньше right, в nums[left] заведомо ноль. А когда индексы совпали, элемент уже стоит там,
// где надо, и обмен был бы сам с собой — его и пропускаем.
// Время: O(n) — один проход, каждый элемент смотрим один раз.
// Память: O(1) — два индекса, изменения идут в том же массиве.
// Ловушка: относительный порядок ненулевых обязан сохраниться, поэтому идём строго слева
// направо. Обмен с конца или сортировка порядок ломают.
func moveZeroes(nums []int) {
	for left, right := 0, 0; right < len(nums); right++ {
		if nums[left] != 0 {
			left++
		} else if nums[right] != 0 {
			nums[left], nums[right] = nums[right], nums[left]
			left++
		}
	}
}

// moveZeroesOverwrite — вариант без обмена: pos указывает, куда писать следующий ненулевой
// элемент. Первый проход переносит все ненулевые в начало, второй забивает хвост нулями.
// Время: O(n), память O(1). Проходов два вместо одного, зато нет обмена и условие читается
// проще. Это та же форма указателя записи, что в задаче 26, только там хвост отбрасывается
// по длине ответа, а здесь его надо занулить.
func moveZeroesOverwrite(nums []int) {
	pos := 0
	for i := 0; i < len(nums); i++ {
		if nums[i] == 0 {
			continue
		}

		nums[pos] = nums[i]
		pos++
	}

	for ; pos < len(nums); pos++ {
		nums[pos] = 0
	}
}
