package main // https://leetcode.com/problems/roman-to-integer/

// romanToInt — вариант с проходом с конца строки.
// Идея: каждый символ сравниваем с соседом справа: меньше соседа — вычитаем,
// иначе прибавляем. Шесть исключений (IV, IX, XL, XC, CD, CM) — это и есть
// "меньший перед большим", перечислять их отдельно не нужно. Идём с конца,
// последний символ всегда прибавляется.
// Время: O(n) — один проход по строке, поиск в map из 7 ключей — O(1).
// Память: O(1) — map фиксированного размера (7 римских символов), от длины строки не зависит.
// Ловушка: равные соседи (III) прибавляются. Если перевернуть условие "меньше — вычесть"
// в "больше или равно — прибавить", нужен >=, а не >.
func romanToInt(s string) int {
	data := map[byte]int{
		'I': 1,
		'V': 5,
		'X': 10,
		'L': 50,
		'C': 100,
		'D': 500,
		'M': 1000,
	}

	out := data[s[len(s)-1]]
	for i := len(s) - 2; i >= 0; i-- {
		if data[s[i]] >= data[s[i+1]] {
			out += data[s[i]]
		} else {
			out -= data[s[i]]
		}
	}

	return out
}

// romanToIntAnother — то же правило, но проход с начала строки.
// Идея: символ меньше соседа справа — вычитаем, иначе прибавляем. Направление обхода
// на результат не влияет: знак символа зависит только от соседа справа, а порядок
// слагаемых в сумме не важен.
// Время: O(n) — один проход по строке, поиск в map из 7 ключей — O(1).
// Память: O(1) — map фиксированного размера (7 римских символов), от длины строки не зависит.
// Ловушка: у последнего символа соседа справа нет. Проверка i < size-1 и закрывает
// выход за границу строки, и отправляет последний символ в сложение.
func romanToIntAnother(s string) int {
	data := map[byte]int{
		'I': 1,
		'V': 5,
		'X': 10,
		'L': 50,
		'C': 100,
		'D': 500,
		'M': 1000,
	}

	size := len(s)
	result := 0
	for i := 0; i < size; i++ {
		if i < size-1 && data[s[i]] < data[s[i+1]] {
			result -= data[s[i]]
		} else {
			result += data[s[i]]
		}
	}

	return result
}
