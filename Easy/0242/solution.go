package main // https://leetcode.com/problems/valid-anagram/description/

// isAnagram — вариант со счётчиками в map.
// Идея: считаем буквы первой строки, затем идём по второй и уменьшаем счётчики.
// Счётчик ушёл в нуль, а буква снова встретилась — она лишняя, значит не анаграмма.
// Проверка равных длин в начале позволяет не проверять остатки счётчиков в конце:
// n декрементов из суммы n без уходов ниже нуля обнуляют все счётчики.
// Время: O(n) — два последовательных прохода, операции с map по ключу-руне O(1).
// Память: O(min(n, размер алфавита)). Для строчных латинских букв это O(1), не больше
// 26 ключей. Для произвольного Unicode ограничением становится длина строки, то есть O(n).
// Ловушка: len считает байты, а range идёт по рунам. Для анаграмм проверка длины в байтах
// всё равно корректна: одинаковые наборы рун дают одинаковое число байт.
func isAnagram(s string, t string) bool {
	if len(s) != len(t) {
		return false
	}

	memory := make(map[rune]int)
	for _, v := range s {
		memory[v]++
	}

	for _, v := range t {
		if memory[v] == 0 {
			return false
		}
		memory[v]--
	}

	return true
}

// isAnagramArrays — вариант с двумя массивами счётчиков.
// Идея: в одном проходе считаем буквы обеих строк в два массива [26]int, затем сравниваем
// счётчики. Индекс буквы — это s[i]-'a', поэтому вариант рассчитан только на строчные
// латинские буквы.
// Время: O(n) — один проход по строкам плюс сравнение 26 ячеек, то есть константа.
// Память: O(1) — размер массивов записан в типе и от длины строк не зависит. В отличие от
// варианта с map, здесь это видно сразу, без рассуждений про размер алфавита.
// Ловушка: для Unicode так нельзя — индекс s[i]-'a' выйдет за границы массива, там нужна
// map. Второй цикл можно не писать: массивы в Go сравнимы, достаточно uniqS == uniqT.
func isAnagramArrays(s string, t string) bool {
	if len(s) != len(t) {
		return false
	}

	uniqS := [26]int{}
	uniqT := [26]int{}

	for i := 0; i < len(s); i++ {
		uniqS[s[i]-'a']++
		uniqT[t[i]-'a']++
	}

	for i := 0; i < 26; i++ {
		if uniqS[i] != uniqT[i] {
			return false
		}
	}

	return true
}
