package main // https://leetcode.com/problems/valid-sudoku/

// Идея: на каждую из девяти строк, девяти столбцов и девяти квадратов заводим набор
// отметок "такая цифра уже встречалась". Проходим по клеткам один раз, пустые пропускаем.
// Если цифра уже отмечена в своей строке, столбце или квадрате, доска неверная.
// Номер квадрата: строка квадрата это i/3, столбец квадрата это j/3. Частное даёт номер
// квадрата, а остаток — позицию внутри него, поэтому i%3 и j%3 тут не подходят.
// Время: O(1) для фиксированной доски 9x9, это 81 клетка. Для доски n x n будет O(n*n) —
// столько в ней клеток.
// Память: O(1) для 9x9. Для n x n это O(n*n) на наборы отметок по строкам, столбцам
// и квадратам.
// Ловушка: цифра лежит в клетке как байт-символ, поэтому индекс отметки считается
// как board[i][j]-'1'. Пустые клетки "." пропускаются до всех проверок, иначе точка
// сама с собой даст ложное совпадение.
func isValidSudoku(board [][]byte) bool {
	rows := [9][9]bool{}
	cols := [9][9]bool{}
	squads := [3][3][9]bool{}

	for i := 0; i < len(board); i++ {
		for j := 0; j < len(board[i]); j++ {
			if board[i][j] == '.' {
				continue
			}

			key := board[i][j] - '1'

			if rows[i][key] {
				return false
			}
			rows[i][key] = true

			if cols[j][key] {
				return false
			}
			cols[j][key] = true

			if squads[i/3][j/3][key] {
				return false
			}
			squads[i/3][j/3][key] = true
		}
	}

	return true
}
