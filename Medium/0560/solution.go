package main // https://leetcode.com/problems/subarray-sum-equals-k/

// Идея: ведём бегущую сумму и блокнот "какое значение бегущей суммы сколько раз
// встречалось". Сумма отрезка — это разность двух бегущих сумм, поэтому отрезков с суммой k,
// которые кончаются на текущем элементе, столько же, сколько раз ранее встречалось значение
// sum-k. На каждом шаге сначала читаем notes[sum-k], затем записываем notes[sum].
// Запись {0: 1} до цикла — это точка до начала массива. Без неё теряются отрезки,
// начинающиеся с первого элемента.
// Время: O(n) — один проход, операции с map в среднем O(1).
// Память: O(n) — в блокноте до n+1 разных значений бегущей суммы, ничем другим они
// не ограничены.
// Ловушка: порядок двух строк. Если записать notes[sum] до чтения, то при k = 0 текущая
// сумма найдёт сама себя. Искать нужно именно sum-k, а не элемент массива.
// Скользящее окно тут не подходит: есть нули и отрицательные числа, и сумма при расширении
// окна не обязана расти.
func subarraySum(nums []int, k int) int {
	sum := 0
	notes := map[int]int{0: 1}
	counter := 0
	for i := 1; i <= len(nums); i++ {
		sum += nums[i-1]

		counter += notes[sum-k]

		notes[sum]++
	}

	return counter
}
