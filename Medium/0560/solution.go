package main // https://leetcode.com/problems/subarray-sum-equals-k/

// Идея: ведём бегущую сумму и блокнот "какое значение бегущей суммы сколько раз
// встречалось". Сумма отрезка — это разность двух бегущих сумм:
//
//	sum_сейчас - sum_раньше = k, значит sum_раньше = sum_сейчас - k
//
// Отрезков с суммой k, которые кончаются на текущем элементе, столько же, сколько раз ранее
// встречалось значение sum-k. На каждом шаге сначала читаем note[sum-k], затем записываем
// note[sum]: "сейчас" для будущих шагов станет "раньше".
// Запись {0: 1} до цикла — это точка до начала массива. Без неё теряются отрезки,
// начинающиеся с первого элемента.
// Время: O(n) — один проход, операции с map в среднем O(1).
// Память: O(n) — в блокноте до n+1 разных значений бегущей суммы, ничем другим они
// не ограничены.
// Ловушка: в равенстве выше нет элементов массива, только бегущие суммы. Подстановка
// nums[i] вместо sum-k — самая частая ошибка здесь, и цикл через range её исключает:
// индекса просто нет. Порядок строк тоже важен: если записать note[sum] до чтения,
// при k = 0 текущая сумма найдёт сама себя.
// Скользящее окно тут не подходит: есть нули и отрицательные числа, и сумма при расширении
// окна не обязана расти.
func subarraySum(nums []int, k int) int {
	sum := 0
	note := map[int]int{0: 1}
	out := 0
	for _, num := range nums {
		sum += num
		out += note[sum-k]
		note[sum]++
	}

	return out
}
